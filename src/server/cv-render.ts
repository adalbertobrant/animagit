/**
 * cv-render.ts — gera Markdown e PDF do currículo
 *
 * PDF: usa o Chrome headless já presente no Remotion (ensureBrowser).
 * Markdown: string pura, sem dependências.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import type { CvData, CvLanguage } from "../shared/cv-types.js";
import { PATHS } from "./paths.js";

// ── Helpers de formatação ────────────────────────────────────────

const fmtDate = (iso: string, lang: CvLanguage): string => {
  try {
    return new Date(iso).toLocaleDateString(lang === "pt" ? "pt-BR" : "en-US", {
      year: "numeric", month: "short",
    });
  } catch {
    return iso.slice(0, 7);
  }
};

const stars = (n: number) => n > 0 ? ` ⭐ ${n}` : "";
const forks = (n: number) => n > 0 ? ` 🍴 ${n}` : "";

// ── Geração de Markdown ──────────────────────────────────────────
export const generateMarkdown = (cv: CvData): string => {
  const { profile, groups, atsAnalysis, generatedAt, language: lang } = cv;

  const L = {
    pt: {
      contact:      "Contato",
      summary:      "Resumo Profissional",
      skills:       "Habilidades Técnicas",
      projects:     "Projetos",
      ats:          "Análise ATS",
      atsScore:     "Score ATS",
      keywords:     "Palavras-chave encontradas",
      strengths:    "Pontos fortes",
      suggestions:  "Sugestões de melhoria",
      aiSummary:    "Resumo gerado por IA",
      commits:      "commits em 2 anos",
      generatedBy:  "Gerado por Anima GitHub",
    },
    en: {
      contact:      "Contact",
      summary:      "Professional Summary",
      skills:       "Technical Skills",
      projects:     "Projects",
      ats:          "ATS Analysis",
      atsScore:     "ATS Score",
      keywords:     "Keywords found",
      strengths:    "Strengths",
      suggestions:  "Improvement suggestions",
      aiSummary:    "AI-generated summary",
      commits:      "commits in 2 years",
      generatedBy:  "Generated by Anima GitHub",
    },
  }[lang];

  const lines: string[] = [];

  // Cabeçalho
  lines.push(`# ${profile.name}`);
  lines.push(`### ${profile.title}`);
  lines.push("");

  // Contato
  lines.push(`## ${L.contact}`);
  if (profile.email)    lines.push(`- 📧 ${profile.email}`);
  if (profile.phone)    lines.push(`- 📱 ${profile.phone}`);
  if (profile.location) lines.push(`- 📍 ${profile.location}`);
  if (profile.linkedin) lines.push(`- 💼 [LinkedIn](${profile.linkedin.startsWith("http") ? profile.linkedin : `https://linkedin.com/in/${profile.linkedin}`})`);
  if (profile.website)  lines.push(`- 🌐 [${profile.website}](${profile.website})`);
  lines.push("");

  // Resumo
  if (profile.summary) {
    lines.push(`## ${L.summary}`);
    lines.push(profile.summary);
    lines.push("");
  }

  // Habilidades
  if (profile.skills.length > 0) {
    lines.push(`## ${L.skills}`);
    // Divide em grupos de 5
    const chunks: string[][] = [];
    for (let i = 0; i < profile.skills.length; i += 5) {
      chunks.push(profile.skills.slice(i, i + 5));
    }
    chunks.forEach(chunk => lines.push(`- ${chunk.join(" · ")}`));
    lines.push("");
  }

  // Projetos por grupo
  lines.push(`## ${L.projects}`);
  for (const group of groups) {
    lines.push(`### ${group.language} — ${group.domain}`);
    lines.push("");
    for (const repo of group.repos) {
      lines.push(`#### [${repo.name}](${repo.url})${stars(repo.stars)}${forks(repo.forks)}`);
      if (repo.description) lines.push(`*${repo.description}*`);
      if (repo.readmeExcerpt) lines.push(`> ${repo.readmeExcerpt}`);
      const meta: string[] = [];
      meta.push(`\`${repo.language}\``);
      if (repo.commitCount > 0) meta.push(`${repo.commitCount} ${L.commits}`);
      meta.push(fmtDate(repo.lastCommitAt, lang));
      if (repo.topics.length > 0) meta.push(repo.topics.slice(0, 5).map(t => `\`${t}\``).join(" "));
      lines.push(meta.filter(Boolean).join(" · "));
      lines.push("");
    }
  }

  // ATS
  if (atsAnalysis) {
    lines.push(`---`);
    lines.push(`## ${L.ats}`);
    lines.push("");
    lines.push(`**${L.atsScore}:** ${atsAnalysis.score}/100`);
    lines.push("");

    if (atsAnalysis.aiSummary) {
      lines.push(`### ${L.aiSummary}`);
      lines.push(atsAnalysis.aiSummary);
      lines.push("");
    }
    if (atsAnalysis.strengths.length > 0) {
      lines.push(`### ${L.strengths}`);
      atsAnalysis.strengths.forEach(s => lines.push(`- ✅ ${s}`));
      lines.push("");
    }
    if (atsAnalysis.suggestions.length > 0) {
      lines.push(`### ${L.suggestions}`);
      atsAnalysis.suggestions.forEach(s => lines.push(`- 💡 ${s}`));
      lines.push("");
    }
    if (atsAnalysis.keywords.length > 0) {
      lines.push(`### ${L.keywords}`);
      lines.push(atsAnalysis.keywords.map(k => `\`${k}\``).join(" "));
      lines.push("");
    }
  }

  // Footer
  lines.push(`---`);
  lines.push(`*${L.generatedBy} · ${new Date(generatedAt).toLocaleDateString()}*`);

  return lines.join("\n");
};

// ── HTML para PDF ────────────────────────────────────────────────
const markdownToHtml = (md: string): string => {
  // Converte markdown básico para HTML sem dependência pesada
  let html = md
    .replace(/^#### (.+)$/gm, "<h4>$1</h4>")
    .replace(/^### (.+)$/gm, "<h3>$1</h3>")
    .replace(/^## (.+)$/gm, "<h2>$1</h2>")
    .replace(/^# (.+)$/gm, "<h1>$1</h1>")
    .replace(/^\*\*(.+?)\*\*$/gm, "<strong>$1</strong>")
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/\*(.+?)\*/g, "<em>$1</em>")
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/^> (.+)$/gm, "<blockquote>$1</blockquote>")
    .replace(/^- (.+)$/gm, "<li>$1</li>")
    .replace(/^---$/gm, "<hr>")
    .replace(/\n\n/g, "</p><p>")
    .replace(/(<li>.*<\/li>\n?)+/g, (m) => `<ul>${m}</ul>`);
  html = `<p>${html}</p>`;
  return html;
};

const buildHtmlDocument = (md: string, profile: CvData["profile"]): string => {
  const body = markdownToHtml(md);
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${profile.name} — CV</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body {
    font-family: 'Segoe UI', Arial, sans-serif;
    font-size: 11pt;
    line-height: 1.6;
    color: #1a1a1a;
    max-width: 800px;
    margin: 0 auto;
    padding: 32px 40px;
  }
  h1 { font-size: 22pt; color: #0d1117; margin-bottom: 2px; }
  h2 { font-size: 13pt; color: #0d3d6e; border-bottom: 2px solid #0d3d6e; margin: 20px 0 8px; padding-bottom: 4px; }
  h3 { font-size: 11pt; color: #1a5f7a; margin: 14px 0 4px; }
  h4 { font-size: 10.5pt; color: #0d1117; margin: 10px 0 2px; }
  h3 + h4 { margin-top: 6px; }
  p { margin: 4px 0 8px; }
  a { color: #0d3d6e; text-decoration: none; }
  code {
    background: #f0f4f8;
    padding: 1px 5px;
    border-radius: 3px;
    font-size: 9pt;
    font-family: 'Courier New', monospace;
  }
  blockquote {
    border-left: 3px solid #ccd6e0;
    padding-left: 10px;
    color: #444;
    font-style: italic;
    margin: 4px 0 8px;
    font-size: 9.5pt;
  }
  ul { padding-left: 18px; margin: 4px 0 8px; }
  li { margin-bottom: 3px; }
  hr { border: none; border-top: 1px solid #ddd; margin: 16px 0; }
  strong { font-weight: 700; }
  em { color: #555; }
  @media print {
    body { padding: 20px 28px; }
    h2 { page-break-before: auto; }
    h4 { page-break-after: avoid; }
  }
</style>
</head>
<body>
${body}
</body>
</html>`;
};

// ── Geração de PDF via Chrome headless ──────────────────────────
export const generatePdf = async (cv: CvData, outputPath: string): Promise<void> => {
  const md   = generateMarkdown(cv);
  const html = buildHtmlDocument(md, cv.profile);

  await mkdir(dirname(outputPath), { recursive: true });
  const tmpHtml = outputPath.replace(/\.pdf$/, ".tmp.html");
  await writeFile(tmpHtml, html, "utf8");

  const { ensureBrowser } = await import("@remotion/renderer") as typeof import("@remotion/renderer");

  let chromePath: string;
  try {
    const result = await ensureBrowser({
      onBrowserDownload: () => ({ version: null, onProgress: () => undefined }),
    });
    chromePath = (result as unknown as { path: string }).path;
  } catch {
    // Fallback: salva HTML se Chrome não estiver disponível
    const htmlOut = outputPath.replace(/\.pdf$/, ".html");
    await writeFile(htmlOut, html, "utf8");
    await import("node:fs/promises").then(fs => fs.unlink(tmpHtml).catch(() => undefined));
    return;
  }

  // Usa child_process para gerar PDF com o Chrome headless
  const { execFile } = await import("node:child_process");
  const { promisify } = await import("node:util");
  const execFileAsync = promisify(execFile);

  try {
    await execFileAsync(chromePath, [
      "--headless=new",
      "--no-sandbox",
      "--disable-setuid-sandbox",
      "--disable-dev-shm-usage",
      `--print-to-pdf=${outputPath}`,
      "--print-to-pdf-no-header",
      `file://${tmpHtml}`,
    ]);
  } finally {
    await import("node:fs/promises").then(fs => fs.unlink(tmpHtml).catch(() => undefined));
  }
};

// ── Salva CV em disco ────────────────────────────────────────────
export const saveCvFiles = async (
  cv: CvData,
  format: "pdf" | "markdown" | "both",
): Promise<{ markdownPath?: string; pdfPath?: string }> => {
  const outDir = resolve(PATHS.root, "out", "cv");
  await mkdir(outDir, { recursive: true });

  const slug = `${cv.profile.name.toLowerCase().replace(/\s+/g, "-")}-cv-${cv.language}`;
  const result: { markdownPath?: string; pdfPath?: string } = {};

  if (format === "markdown" || format === "both") {
    const mdPath = resolve(outDir, `${slug}.md`);
    const md     = generateMarkdown(cv);
    await writeFile(mdPath, md, "utf8");
    result.markdownPath = mdPath;
  }

  if (format === "pdf" || format === "both") {
    const pdfPath = resolve(outDir, `${slug}.pdf`);
    await generatePdf(cv, pdfPath);
    result.pdfPath = pdfPath;
  }

  return result;
};
